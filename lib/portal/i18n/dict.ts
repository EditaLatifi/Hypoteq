/**
 * The eleven Portal_Status__c values in one language, plus every older status name worded as
 * the value that replaced it: stored notifications still name those (lib/portal/status.ts).
 */
function statusTexts(texts: Record<CaseStatus, string>): Record<string, string> {
  const out: Record<string, string> = { ...texts };
  for (const [old, now] of Object.entries(LEGACY_STATUSES)) out[old] = texts[now];
  return out;
}

