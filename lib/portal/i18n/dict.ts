export const DICTS: Record<Locale, Dict> = { de, en, fr, it };

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

/** Salesforce Korrespondenzsprache__c values ("Deutsch", "Französisch", …) to a locale. */
export function localeFromSalesforce(v: string | null | undefined): Locale | null {
  const s = (v || "").toLowerCase();
  if (s.startsWith("deu") || s === "de" || s.startsWith("ger")) return "de";
  if (s.startsWith("fr")) return "fr";
  if (s.startsWith("it")) return "it";
  if (s.startsWith("en")) return "en";
  return null;
}
